"""Generate anti-aliased VLW fonts (LovyanGFX smooth fonts) from Inter TTFs.

Output: src/ui/fonts_gen.h  (C arrays, usable on ESP32 flash and in the SDL sim)
Run:    python tools/make_fonts.py
"""
import os
import struct
from PIL import ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
FONT_DIR = os.path.join(HERE, "fonts")
OUT = os.path.join(HERE, "..", "src", "ui", "fonts_gen.h")

TEXT = "".join(chr(c) for c in range(0x20, 0x7F)) + "áéíóúñÁÉÍÓÚÑüÜ¿¡°·•–—…"
NUM = " 0123456789%.,:-+/$kKMBhdmsx<>"

# (c identifier, ttf, pixel size, charset)
FONTS = [
    ("font_xs", "Inter-SemiBold.ttf", 10, TEXT),
    ("font_sm", "Inter-Medium.ttf", 12, TEXT),
    ("font_md", "Inter-SemiBold.ttf", 14, TEXT),
    ("font_lg", "Inter-Bold.ttf", 18, TEXT),
    ("font_xl", "Inter-Bold.ttf", 22, NUM),
    ("font_hero", "Inter-Bold.ttf", 38, NUM),
]


def build_vlw(ttf, size, chars):
    font = ImageFont.truetype(os.path.join(FONT_DIR, ttf), size)
    ascent, descent = font.getmetrics()
    glyphs = []
    for ch in sorted(set(chars), key=ord):
        adv = int(round(font.getlength(ch)))
        if ch == " ":
            glyphs.append((ord(ch), 0, 0, adv, 0, 0, b""))
            continue
        mask, (ox, oy) = font.getmask2(ch, mode="L")
        w, h = mask.size
        data = bytes(mask)  # type: ignore[arg-type]
        dy = ascent - oy  # top of bitmap above baseline
        glyphs.append((ord(ch), h, w, adv, dy, ox, data))

    out = bytearray(struct.pack(">6i", len(glyphs), 11, size, 0, ascent, descent))
    for code, h, w, adv, dy, dx, _ in glyphs:
        out += struct.pack(">7i", code, h, w, adv, dy, dx, 0)
    for g in glyphs:
        out += g[6]
    return bytes(out)


def main():
    lines = [
        "// AUTO-GENERATED by tools/make_fonts.py - do not edit.",
        "// Inter (c) The Inter Project Authors, SIL Open Font License 1.1",
        "#pragma once",
        "#include <stdint.h>",
        "",
    ]
    total = 0
    for name, ttf, size, chars in FONTS:
        blob = build_vlw(ttf, size, chars)
        total += len(blob)
        lines.append(f"// {ttf} {size}px, {len(set(chars))} glyphs, {len(blob)} bytes")
        lines.append(f"static const uint8_t {name}_vlw[] = {{")
        for i in range(0, len(blob), 24):
            lines.append("  " + ",".join(str(b) for b in blob[i:i + 24]) + ",")
        lines.append("};")
        lines.append("")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {os.path.normpath(OUT)} ({total} bytes of font data)")


if __name__ == "__main__":
    main()
